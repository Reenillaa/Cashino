import React, { useState } from 'react';
import { StyleSheet, TextInput, View } from 'react-native';
import * as Clipboard from 'expo-clipboard';
import { Button, PressableScale, T } from '@/design/components';
import { useTheme } from '@/design/theme';
import { radius } from '@/design/tokens';
import { useT } from '@/i18n';
import { useFairness } from '@/state/fairness';
import { fairRng, hashServerSeed } from '@/engine/rng/rng.ts';

function Field({ label, value }: { label: string; value: string }) {
  const { c } = useTheme();
  return (
    <PressableScale onPress={() => void Clipboard.setStringAsync(value)} scaleTo={0.99} accessibilityLabel={`${label}: ${value}`} style={[styles.field, { backgroundColor: c.surface2 }]}>
      <T variant="caption" color="text3">{label}</T>
      <T style={{ fontFamily: 'GeistMono_500Medium', fontSize: 12, marginTop: 4 }} color="text2" selectable>{value}</T>
    </PressableScale>
  );
}

/** Shows the provably-fair seeds, lets the player rotate them and verify previous rounds. */
export function FairnessPanel({ online, locked }: { online: boolean; locked: boolean }) {
  const { t, lang } = useT();
  const { c } = useTheme();
  const f = useFairness();
  const [client, setClient] = useState(f.clientSeed);
  const [nonce, setNonce] = useState(f.previous ? String(f.previous.lastNonce) : '1');
  const prev = f.previous;
  const floats = prev ? Array.from({ length: 4 }, (_, i) => i).map(() => 0) : [];
  if (prev) {
    const r = fairRng({ serverSeed: prev.serverSeed, clientSeed: prev.clientSeed, nonce: Number(nonce) || 1 });
    for (let i = 0; i < floats.length; i++) floats[i] = r.float();
  }
  return (
    <View style={{ gap: 10 }}>
      <T variant="footnote" color="text2">{t('play.verifyHint')}</T>
      {online ? (
        <T variant="footnote" color="text3">
          {lang === 'en'
            ? 'Online rounds are generated by the server with a secure random source; each round is logged with its result.'
            : 'Las rondas online las genera el servidor con una fuente aleatoria segura; cada ronda queda registrada con su resultado.'}
        </T>
      ) : null}
      <Field label={t('play.serverSeedHash')} value={f.serverSeedHash} />
      <View style={[styles.field, { backgroundColor: c.surface2 }]}>
        <T variant="caption" color="text3">{t('play.clientSeed')}</T>
        <TextInput value={client} onChangeText={setClient} autoCapitalize="none" autoCorrect={false} accessibilityLabel={t('play.clientSeed')} style={{ color: c.text, fontFamily: 'GeistMono_500Medium', fontSize: 13, marginTop: 4, padding: 0 }} />
      </View>
      <Field label={t('play.nonce')} value={String(f.nonce)} />
      <Button title={t('play.rotateSeed')} kind="secondary" size="md" disabled={locked} onPress={() => f.setClientSeed(client)} />
      {prev ? (
        <View style={{ gap: 10, marginTop: 8 }}>
          <T variant="caption" color="text3">{t('play.previousSeed')}</T>
          <Field label="Server seed" value={prev.serverSeed} />
          <T variant="footnote" color={hashServerSeed(prev.serverSeed) === prev.serverSeedHash ? 'win' : 'loss'}>
            SHA-256(server seed) {hashServerSeed(prev.serverSeed) === prev.serverSeedHash ? '= ✓' : '≠ ✗'} {prev.serverSeedHash.slice(0, 16)}…
          </T>
          <View style={[styles.field, { backgroundColor: c.surface2 }]}>
            <T variant="caption" color="text3">{t('play.nonce')} (1–{prev.lastNonce})</T>
            <TextInput value={nonce} onChangeText={(s) => setNonce(s.replace(/\D/g, ''))} keyboardType="number-pad" accessibilityLabel={t('play.nonce')} style={{ color: c.text, fontFamily: 'GeistMono_500Medium', fontSize: 13, marginTop: 4, padding: 0 }} />
          </View>
          <T style={{ fontFamily: 'GeistMono_500Medium', fontSize: 12 }} color="text2">
            u₀…u₃ = {floats.map((x) => x.toFixed(8)).join('  ')}
          </T>
        </View>
      ) : null}
    </View>
  );
}

const styles = StyleSheet.create({
  field: { padding: 12, borderRadius: radius.sm },
});
